use meiki_application::ApplicationService;

pub(crate) fn read(service: &ApplicationService, content_hash: &str) -> Result<Vec<u8>, String> {
    service
        .read_managed_audio(content_hash)
        .map_err(|_| "Audio transport failed.".to_owned())
}

